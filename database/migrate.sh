#!/usr/bin/env bash
# =====================================================================
# Hope, Inc. ERP: database migration runner (S1-DBA-01, S4-DBA-06)
#
# No Docker needed. You only need the PostgreSQL client (psql):
#   Mac:      brew install postgresql@17   (then follow brew's PATH hint)
#   Windows:  install PostgreSQL from postgresql.org, tick "Command Line Tools",
#             and run this script from Git Bash
#
# Point it at your Supabase database (Supabase → Connect → "Session pooler"):
#   export HOPE_DB_URL='postgresql://postgres.xxxx:PASSWORD@aws-0-xx.pooler.supabase.com:5432/postgres'
#
# Usage:
#   ./migrate.sh              apply new migrations, then the seeds
#   ./migrate.sh --status     list which migrations are applied
#   ./migrate.sh --demo       also load seeds/demo (sample HR data)
#   ./migrate.sh --test       run every file in tests/ and fail on any FAIL
#   ./migrate.sh --rebuild    WIPE the public schema and build it again from 01
#   ./migrate.sh --bundle     write dist/hope-all-in-one.sql for the SQL Editor
#
# Each migration runs in one transaction: it either applies fully or not at all.
# Applied files are recorded in public.schema_migrations with a checksum, so an
# edited migration is reported instead of silently re-run.
# =====================================================================
set -euo pipefail
cd "$(dirname "$0")"

DEMO=0; TEST=0; REBUILD=0; STATUS=0; BUNDLE=0
for arg in "$@"; do
  case "$arg" in
    --demo) DEMO=1 ;; --test) TEST=1 ;; --rebuild) REBUILD=1 ;;
    --status) STATUS=1 ;; --bundle) BUNDLE=1 ;;
    -h|--help) sed -n '2,24p' "$0"; exit 0 ;;
    *) echo "Unknown option: $arg (try --help)" >&2; exit 1 ;;
  esac
done

checksum() { if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }

# --bundle needs no database: it just joins the files in order.
if [ "$BUNDLE" = 1 ]; then
  mkdir -p dist
  OUT=dist/hope-all-in-one.sql
  {
    echo "-- Hope, Inc. ERP: every migration and seed in one file."
    echo "-- Generated by ./migrate.sh --bundle on $(date +%Y-%m-%d). Do not edit; edit migrations/ instead."
    echo "-- Paste into Supabase → SQL Editor and click Run, on an EMPTY project only."
    for f in migrations/*.sql seeds/*.sql; do
      echo; echo "-- ===================================================================="
      echo "-- FILE: $f"; echo "-- ===================================================================="
      cat "$f"
    done
  } > "$OUT"
  echo "Wrote $OUT ($(wc -l < "$OUT") lines)"
  [ "$DEMO$TEST$REBUILD$STATUS" = "0000" ] && exit 0
fi

if [ -z "${HOPE_DB_URL:-}" ]; then
  echo "Set HOPE_DB_URL first (Supabase → Connect → Session pooler connection string)." >&2
  exit 1
fi
command -v psql >/dev/null || { echo "psql not found. Install the PostgreSQL client first (see the top of this file)." >&2; exit 1; }

PSQL=(psql "$HOPE_DB_URL" -X -q -v ON_ERROR_STOP=1 --no-psqlrc)
QUIET=(-c "SET client_min_messages = warning")
q() { "${PSQL[@]}" -At -c "SET client_min_messages = warning; $1"; }

if [ "$REBUILD" = 1 ]; then
  echo "This DELETES every table, view and function in the public schema of:"
  echo "  $(q "select current_database() || ' on ' || coalesce(inet_server_addr()::text, 'local socket')")"
  if [ "${HOPE_YES:-}" != 1 ]; then
    read -r -p "Type REBUILD to continue: " ans
    [ "$ans" = "REBUILD" ] || { echo "Cancelled."; exit 1; }
  fi
  "${PSQL[@]}" <<'SQL'
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
DROP SCHEMA public CASCADE;
CREATE SCHEMA public;
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON SCHEMA public TO postgres, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES    TO postgres, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON FUNCTIONS TO postgres, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO postgres, service_role;
SQL
  echo "Public schema wiped."
fi

q "CREATE TABLE IF NOT EXISTS public.schema_migrations (
     filename   TEXT PRIMARY KEY,
     checksum   TEXT NOT NULL,
     applied_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     applied_by TEXT NOT NULL DEFAULT session_user);
   ALTER TABLE public.schema_migrations ENABLE ROW LEVEL SECURITY;
   REVOKE ALL ON public.schema_migrations FROM anon, authenticated;" >/dev/null

if [ "$STATUS" = 1 ]; then
  for f in migrations/*.sql; do
    name=$(basename "$f")
    saved=$(q "select checksum from schema_migrations where filename = '$name'")
    if [ -z "$saved" ]; then echo "  pending   $name"
    elif [ "$saved" = "$(checksum "$f")" ]; then echo "  applied   $name"
    else echo "  CHANGED   $name  (edited after it was applied: add a new migration instead)"; fi
  done
  exit 0
fi

applied=0
for f in migrations/*.sql; do
  name=$(basename "$f"); sum=$(checksum "$f")
  saved=$(q "select checksum from schema_migrations where filename = '$name'")
  if [ -z "$saved" ]; then   # applied before under an older name with the same number (e.g. 001_… → 01_…)?
    old=$(q "select filename from schema_migrations where split_part(filename, '_', 1) ~ '^[0-9]+$'
             and split_part(filename, '_', 1)::int = $((10#${name%%_*}))")
    if [ -n "$old" ]; then
      q "update schema_migrations set filename = '$name', checksum = '$sum' where filename = '$old'" >/dev/null
      echo "  renamed   $old → $name (already applied)"; continue
    fi
  fi
  if [ -n "$saved" ]; then
    [ "$saved" != "$sum" ] && echo "  warning: $name changed after it was applied. Not re-run; put the change in a new migration." >&2
    continue
  fi
  echo "  applying  $name"
  "${PSQL[@]}" --single-transaction "${QUIET[@]}" \
    -f "$f" \
    -c "INSERT INTO schema_migrations (filename, checksum) VALUES ('$name', '$sum')" >/dev/null
  applied=$((applied + 1))
done
echo "Migrations: $applied applied, $(q "select count(*) from schema_migrations") total."

for f in seeds/*.sql; do
  echo "  seeding   $(basename "$f")"
  "${PSQL[@]}" --single-transaction "${QUIET[@]}" -f "$f"
done

if [ "$DEMO" = 1 ]; then
  for f in seeds/demo/*.sql; do
    echo "  demo data $(basename "$f")"
    "${PSQL[@]}" --single-transaction "${QUIET[@]}" -f "$f"
  done
fi

if [ "$TEST" = 1 ]; then
  fails=0
  for f in tests/*.sql; do
    echo; echo "== $(basename "$f")"
    out=$("${PSQL[@]}" -P pager=off "${QUIET[@]}" -f "$f" 2>&1)
    echo "$out"
    grep -qE '\| *FAIL *(\||$)' <<<"$out" && fails=$((fails + 1))
  done
  echo
  if [ "$fails" -gt 0 ]; then echo "Tests: $fails file(s) with a FAIL."; exit 1; fi
  echo "Tests: all passed."
fi
